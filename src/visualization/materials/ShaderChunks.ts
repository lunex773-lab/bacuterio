/** GLSL helpers shared by the custom materials. */
export const NOISE_GLSL = /* glsl */ `
float pw_hash13(vec3 p3) {
  p3 = fract(p3 * 0.1031);
  p3 += dot(p3, p3.zyx + 31.32);
  return fract((p3.x + p3.y) * p3.z);
}
vec3 pw_hash33(vec3 p3) {
  p3 = fract(p3 * vec3(0.1031, 0.1030, 0.0973));
  p3 += dot(p3, p3.yxz + 33.33);
  return fract((p3.xxy + p3.yxx) * p3.zyx);
}
float pw_noise(vec3 p) {
  vec3 i = floor(p);
  vec3 f = fract(p);
  f = f * f * (3.0 - 2.0 * f);
  return mix(
    mix(mix(pw_hash13(i), pw_hash13(i + vec3(1,0,0)), f.x), mix(pw_hash13(i + vec3(0,1,0)), pw_hash13(i + vec3(1,1,0)), f.x), f.y),
    mix(mix(pw_hash13(i + vec3(0,0,1)), pw_hash13(i + vec3(1,0,1)), f.x), mix(pw_hash13(i + vec3(0,1,1)), pw_hash13(i + vec3(1,1,1)), f.x), f.y),
    f.z);
}
float pw_fbm(vec3 p) {
  float a = 0.5;
  float s = 0.0;
  for (int i = 0; i < 4; i++) { s += a * pw_noise(p); p *= 2.03; a *= 0.5; }
  return s;
}
// distance to nearest feature point (F1) and second nearest (F2)
vec2 pw_worley(vec3 p) {
  vec3 i = floor(p);
  vec3 f = fract(p);
  float d1 = 8.0;
  float d2 = 8.0;
  for (int z = -1; z <= 1; z++)
  for (int y = -1; y <= 1; y++)
  for (int x = -1; x <= 1; x++) {
    vec3 g = vec3(float(x), float(y), float(z));
    vec3 o = pw_hash33(i + g);
    vec3 r = g + o - f;
    float d = dot(r, r);
    if (d < d1) { d2 = d1; d1 = d; } else if (d < d2) { d2 = d; }
  }
  return vec2(sqrt(d1), sqrt(d2));
}
vec2 pw_worley2(vec2 p) {
  vec2 i = floor(p);
  vec2 f = fract(p);
  float d1 = 8.0;
  float d2 = 8.0;
  for (int y = -1; y <= 1; y++)
  for (int x = -1; x <= 1; x++) {
    vec2 g = vec2(float(x), float(y));
    vec2 o = pw_hash33(vec3(i + g, 7.0)).xy;
    vec2 r = g + o - f;
    float d = dot(r, r);
    if (d < d1) { d2 = d1; d1 = d; } else if (d < d2) { d2 = d; }
  }
  return vec2(sqrt(d1), sqrt(d2));
}
`;
